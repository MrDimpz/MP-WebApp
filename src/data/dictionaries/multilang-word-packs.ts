export function getMultiLangFeaturedSeeds(
  code: DictionaryLanguageCode,
  size: number,
): string[] {
  const pack = getMultiLangPack(code);
  if (!pack) return [];
  if (size === 3) return pack.featured3x3;
  if (size === 4) return pack.featured4x4;
  return pack.featured5x5;
}

