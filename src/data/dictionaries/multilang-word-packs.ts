function parseDrawingPrompts(list: string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const raw of list) {
    const clean = raw.trim().replace(/\s+/g, " ").toLowerCase();
    const key = stripDiacritics(clean);
    if (clean.length >= 2 && !seen.has(key)) {
      seen.add(key);
      out.push(clean);
    }
  }
  return out;
}
function buildCleanWordList(raw: string, prompts: string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  const add = (token: string) => {
    const clean = stripDiacritics(token).toUpperCase().replace(/[^A-Z]/g, "");
    if (clean.length >= 3 && clean.length <= 10 && !seen.has(clean)) {
      seen.add(clean);
      out.push(clean);
    }
  };
  for (const token of raw.split(/\s+/)) {
    if (token) add(token);
  }
  for (const prompt of prompts) {
    if (!prompt.includes(" ") && !prompt.includes("-")) {
      add(prompt);
    }
  }
  return out;
}
